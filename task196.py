# Список тестів: кожен тест містить [x1, y1, x2, y2]
test_cases = [
    [1, 1, 3, 3]  # згідно з прикладом на скріншоті
]

for x1, y1, x2, y2 in test_cases:
    # Рахуємо різницю між координатами по горизонталі та вертикалі
    # Функція abs() робить число додатним (модуль)
    dx = abs(x1 - x2)
    dy = abs(y1 - y2)
    
    # Король ходить на 1 клітинку, тобто різниця не має перевищувати 1,
    # і клітинки не повинні бути однаковими (сума ходів > 0)
    if max(dx, dy) == 1:
        print("Yes")
    else:
        print("No")